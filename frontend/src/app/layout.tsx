import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { AppToaster } from "@/components/app-toaster";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const themeInitScript = `(function(){try{document.documentElement.classList.toggle('dark',(localStorage.getItem('jh-theme')||'dark')==='dark');}catch(e){document.documentElement.classList.add('dark');}})();`;

export const metadata: Metadata = {
  title: {
    default: "Verdant",
    template: "%s | Verdant",
  },
  description: "Verdant is an autonomous job-hunting agent that finds roles, tailors applications, and keeps you in control.",
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeInitScript }} />
      </head>
      <body className="min-h-full flex flex-col">
        {children}
        <AppToaster />
      </body>
    </html>
  );
}
